// Writes src/lib/content/fonts.generated.ts from assets/fonts/*.woff (base64),
// so the fonts ship inside the server bundle on every host, Vercel included.
// Run after changing assets/fonts: npx tsx scripts/build-fonts.ts
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const files = readdirSync("assets/fonts").filter((f) => f.endsWith(".woff")).sort();
const body = files.map((f) => `  "${f}": "${readFileSync(`assets/fonts/${f}`).toString("base64")}",`).join("\n");
writeFileSync(
  "src/lib/content/fonts.generated.ts",
  `// Generated by scripts/build-fonts.ts from assets/fonts (SIL OFL 1.1: assets/fonts/OFL-*.txt). Do not edit.\nexport const FONT_FILES: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`fonts.generated.ts: ${files.length} fonts`);
